def synthesize_audio():
    print("[AUDIO] Synthesizing Hindi neural voice...")
    tmp_mp3 = "/tmp/sovereign_100_interconnection.mp3"
    try:
        # Try edge-tts first
        cmd = [
            "edge-tts",
            "--voice", "hi-IN-MadhurNeural",
            "--rate", "+10%",
            "--text", AUDIO_TEXT,
            "--write-media", tmp_mp3
        ]
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        if res.returncode != 0 or not os.path.exists(tmp_mp3) or os.path.getsize(tmp_mp3) < 1000:
            raise RuntimeError("edge-tts failed: " + res.stderr)
        print("[AUDIO] edge-tts synthesis successful!")
    except Exception as e:
        print(f"[AUDIO] edge-tts fallback triggered: {e}")
        tmp_aiff = "/tmp/sovereign_speech.aiff"
        subprocess.run(["say", "-v", "Rishi", "-r", "210", "-o", tmp_aiff, AUDIO_TEXT], check=True)
        subprocess.run(["ffmpeg", "-y", "-i", tmp_aiff, "-b:a", "64k", tmp_mp3], check=True)
        if os.path.exists(tmp_aiff):
            os.remove(tmp_aiff)
        print("[AUDIO] Native macOS Rishi neural fallback successful!")

    with open(tmp_mp3, "rb") as f:
        b64_audio = base64.b64encode(f.read()).decode("utf-8")

    if os.path.exists(tmp_mp3):
        os.remove(tmp_mp3)

    return b64_audio

if __name__ == "__main__":
    b64 = synthesize_audio()
    out_b64_path = "/tmp/interconnection_audio_b64.txt"
    with open(out_b64_path, "w") as f:
        f.write(b64)
    print(f"[AUDIO] Audio encoded to base64 ({len(b64)} chars) and saved to {out_b64_path}")
