    with open(SCRIPT_PATH, "w", encoding="utf-8") as f:
        f.write(MASTERCLASS_SCRIPT)
    print(f"  ✓ Script written to {SCRIPT_PATH} ({len(MASTERCLASS_SCRIPT.split())} words)")

    print("[2] Synthesizing speech with edge-tts (Voice: hi-IN-SwaraNeural)...")
    cmd = [
        "edge-tts",
        "--voice", "hi-IN-SwaraNeural",
        "--file", str(SCRIPT_PATH),
        "--write-media", str(AUDIO_PATH)
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print("Error synthesizing speech:", res.stderr)
        sys.exit(1)
    
    audio_size = os.path.getsize(AUDIO_PATH)
    print(f"  ✓ Audio synthesized: {AUDIO_PATH} ({audio_size:,} bytes)")
    return audio_size


